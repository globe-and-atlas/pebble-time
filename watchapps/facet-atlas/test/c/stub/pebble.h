// Compile-only stand-in for <pebble.h> so `make typecheck` can catch C
// errors in src/c/main.c without the SDK. It declares only what main.c
// uses, with signatures as documented for SDK 4. It is NOT the SDK: the
// authoritative check is `pebble build` (see RELEASE.md).
