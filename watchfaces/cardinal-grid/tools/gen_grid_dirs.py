#!/usr/bin/env python3
"""Generate src/c/grid/grid_dirs.h: sin/cos of every 5 degrees in Q15.

Using a constant table (rather than the SDK's sin_lookup) keeps the grid bit-identical
between the watch and the host tests, and removes any doubt about trig sign conventions.
"""
import math
import sys
from pathlib import Path

N = 72
OUT = Path(__file__).resolve().parent.parent / "src/c/grid/grid_dirs.h"

rows = []
for k in range(N):
    a = 2 * math.pi * k / N
    rows.append("{%d, %d}" % (round(math.sin(a) * 32767), round(math.cos(a) * 32767)))
lines = []
for i in range(0, N, 6):
    lines.append("  " + ", ".join(rows[i:i + 6]))
text = ("#pragma once\n/* GENERATED by tools/gen_grid_dirs.py. {sin, cos} of k * 360/%d degrees, Q15. */\n"
        "#include <stdint.h>\n#define GRID_DIRS %d\n"
        "static const struct { int16_t s, c; } grid_dir_table[GRID_DIRS] = {\n%s\n};\n" % (N, N, ",\n".join(lines)))
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else "grid_dirs.h is stale")
OUT.write_text(text)
print("wrote", OUT.name)
